/**
 * Prepare admin pages header
 *
 * @return array
 */
function nssuiviprodAdminPrepareHead()
{
	global $db, $langs, $conf, $user;

	$langs->loadLangs(array("admin", "nsinfo@nsinfo", "nssuiviprod@nssuiviprod"));

	$h = 0;
	$head = array();

	$head[$h][0] = dol_buildpath("/nssuiviprod/admin/setup.php", 1);
	$head[$h][1] = '<i class="fas fa-cogs paddingright pictofixedwidth valignmiddle" style="color: #5A2D82"></i>' . $langs->trans("Settings");
	$head[$h][2] = 'settings';
	$h++;

	// Main tab of the extrafields of the objects (one sub-tab per object: nssuiviprodExtrafieldsPrepareHead())
	$nbextrafields = 0;
	$extrafieldshead = nssuiviprodExtrafieldsPrepareHead($nbextrafields);
	if (count($extrafieldshead)) {
		$head[$h][0] = $extrafieldshead[0][0];
		$head[$h][1] = '<i class="fas fa-th-list paddingright pictofixedwidth valignmiddle" style="color: #22A7D8"></i>'.$langs->trans('ExtraFields');
		if ($nbextrafields > 0) {
			$head[$h][1] .= '<span class="badge marginleftonlyshort">'.$nbextrafields.'</span>';
		}
		$head[$h][2] = 'extrafields';
		$h++;
	}

	// Tabs of the NSINFO framework: their pages are for the administrators only
	if ($user->admin) {
		$head[$h][0] = dol_buildpath("/nsinfo/admin/changelog_module.php?namemodule=nssuiviprod", 1);
		$head[$h][1] = '<i class="fas fa-code-branch paddingright pictofixedwidth valignmiddle" style="color: #3879B2"></i>' . $langs->trans("NSINFOChangeLog");
		$head[$h][2] = 'changelog';
		$h++;


		$head[$h][0] = dol_buildpath("/nsinfo/admin/about_module.php?namemodule=nssuiviprod", 1);
		$head[$h][1] = '<i class="fab fa-readme paddingright pictofixedwidth valignmiddle" style="color: #14182B"></i>' . $langs->trans("About");
		$head[$h][2] = 'about';
		$h++;
	}

	complete_head_from_modules($conf, $langs, null, $head, $h, 'nssuiviprod');

	return $head;
}

/**
 * Prepare the sub-tabs of the extrafields of the objects of the module (setup, tab "Extrafields")
 *
 * @param	int		$total		Total number of extrafields of the objects (output)
 * @return	array<int,array<int,string>>
 */
function nssuiviprodExtrafieldsPrepareHead(&$total = 0)
{
	global $db, $langs;

	require_once DOL_DOCUMENT_ROOT.'/core/class/extrafields.class.php';
	$langs->loadLangs(array("admin", "nssuiviprod@nssuiviprod"));

	// Objects of the module with extrafields: key of the object => array(translation key of the label, picto of the object)
	$objects = array(
		// BEGIN OBJECTS WITH EXTRAFIELDS
		'site' => array('Sites', 'fa-globe_fas_#3879B2'),
		'siteurl' => array('SiteUrls', 'fa-link_fas_#22A7D8'),
		'siteplugin' => array('SitePlugins', 'fa-puzzle-piece_fas_#5A2D82'),
		'siteversion' => array('SiteVersions', 'fa-code-branch_fas_#14182B'),
		// END OBJECTS WITH EXTRAFIELDS
	);

	$extrafields = new ExtraFields($db);
	$total = 0;
	$h = 0;
	$head = array();
	foreach ($objects as $objectkey => $objectdesc) {
		list($objectlabel, $objectpicto) = (is_array($objectdesc) ? $objectdesc : array($objectdesc, ''));
		$extrafields->fetch_name_optionals_label('nssuiviprod_'.$objectkey);
		$nb = (isset($extrafields->attributes['nssuiviprod_'.$objectkey]['label']) && is_countable($extrafields->attributes['nssuiviprod_'.$objectkey]['label'])) ? count($extrafields->attributes['nssuiviprod_'.$objectkey]['label']) : 0;
		$total += $nb;
		$head[$h][0] = dol_buildpath('/nssuiviprod/admin/'.$objectkey.'_extrafields.php', 1);
		$head[$h][1] = ($objectpicto ? img_picto('', $objectpicto, 'class="pictofixedwidth"') : '').$langs->trans($objectlabel).($nb > 0 ? '<span class="badge marginleftonlyshort">'.$nb.'</span>' : '');
		$head[$h][2] = $objectkey.'_extrafields';
		$h++;
	}

	return $head;
}

/**
 * Return the URL of the setup page of a dictionary of the module (Setup > Dictionaries)
 *
 * @param	string	$tablename	Dictionary table without prefix (example 'c_nssuiviprod_typesite')
 * @return	string				URL
 */
function nssuiviprodDictionaryUrl($tablename)
{
	require_once DOL_DOCUMENT_ROOT.'/core/lib/admin.lib.php';

	// Highest id of the core dictionaries, read in admin/dict.php ("const DICT_xxx = n;" or "$tabname[n] = ...")
	$maxcoreid = 0;
	$src = (string) @file_get_contents(DOL_DOCUMENT_ROOT.'/admin/dict.php');
	if (preg_match_all('/(?:const\s+DICT_\w+\s*=\s*|\$tabname\[)(\d+)/', $src, $matches)) {
		$maxcoreid = max(array_map('intval', $matches[1]));
	}

	$taborder = $tabname = $tablib = $tabsql = $tabsqlsort = $tabfield = $tabfieldvalue = $tabfieldinsert = $tabrowid = $tabcond = $tabhelp = $tabcomplete = array();
	$taborder[] = $maxcoreid;
	$tabname[$maxcoreid] = 'core';
	complete_dictionary_with_modules($taborder, $tabname, $tablib, $tabsql, $tabsqlsort, $tabfield, $tabfieldvalue, $tabfieldinsert, $tabrowid, $tabcond, $tabhelp, $tabcomplete);

	foreach ($tabname as $id => $name) {
		if (preg_replace('/^'.preg_quote(MAIN_DB_PREFIX, '/').'/', '', $name) == $tablename) {
			return DOL_URL_ROOT.'/admin/dict.php?id='.((int) $id);
		}
	}

	return DOL_URL_ROOT.'/admin/dict.php';
}

