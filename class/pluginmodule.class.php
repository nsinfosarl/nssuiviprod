	/**
	 * Search products on the Dolistore (public API used by Dolibarr, see admin/remotestore)
	 *
	 * @param	string	$search		Text to search (at least 2 characters)
	 * @return	array<int,array<string,mixed>>|null	Products found (id, label, module_version...), null if the Dolistore can't be reached
	 */
	public static function searchDolistore($search)
	{
		static $cache = array();

		$search = trim((string) $search);
		if (dol_strlen(str_replace(' ', '', $search)) < 2) {
			return array();
		}
		if (array_key_exists($search, $cache)) {
			return $cache[$search];
		}
		require_once DOL_DOCUMENT_ROOT.'/core/lib/geturl.lib.php';
		// URL of the API in the setup of the module, otherwise the one of Dolibarr (Dolibarr 20 and lower force it to the
		// former PrestaShop webservice, without /api: the new API is then used)
		$apiurl = getDolGlobalString('NSSUIVIPROD_DOLISTORE_API_URL');
		$apikey = '';
		if ($apiurl === '') {
			$apiurl = getDolGlobalString('MAIN_MODULE_DOLISTORE_API_SRV');
			$apikey = getDolGlobalString('MAIN_MODULE_DOLISTORE_API_KEY');
			if (!preg_match('/\/api(\/|$)/i', $apiurl)) {
				$apiurl = 'https://www.dolistore.com/api/';
				$apikey = '';
			}
		}
		if ($apikey === '') {
			$apikey = 'dolistorepublicapi';
		}
		$url = $apiurl.(preg_match('/\/$/', $apiurl) ? '' : '/').'products?'.http_build_query(array('search' => $search, 'limit' => 20, 'page' => 1, 'lang' => 'fr_FR', 'apikey' => $apikey));
		$response = getURLContent($url, 'GET', '', 1, array('DOLAPIKEY: '.$apikey), array('https'), 0, -1, 5, 10);
		if (empty($response['http_code']) || $response['http_code'] != 200) {
			return null;	// Not cached: the Dolistore may answer at the next call
		}
		$data = json_decode((string) $response['content'], true);
		$cache[$search] = (is_array($data) && !empty($data['products']) && is_array($data['products'])) ? $data['products'] : array();

		return $cache[$search];
	}

	/**
	 * Get the current version of the module on the Dolistore and save it (with the Dolistore id and label of the product
	 * and the date of the check). Once the module is identified on the Dolistore, one search on the exact label of the
	 * product is enough; otherwise the product is the only one whose label begins with the technical name or the label.
	 * The Dolistore is asked once a day at most for a module, unless the check is forced (button of the user) or the
	 * setup allows several checks a day.
	 *
	 * @param	User		$user				User that checks
	 * @param	int			$skipnotfounddays	Do not search again a module not found on the Dolistore during the last days (0=always search)
	 * @param	int<0,1>	$force				1=ask the Dolistore even if the module was already checked today
	 * @return	int<-1,3>						1 if found, 0 if not found, 2 if skipped (not found recently), 3 if skipped (already checked today), -1 if error (Dolistore not reachable)
	 */
	public function checkDolistoreVersion(User $user, $skipnotfounddays = 0, $force = 0)
	{
		global $langs;

		$lastcheck = (!empty($this->dolistore_date) ? (int) $this->dolistore_date : 0);
		if (empty($force) && $lastcheck && !getDolGlobalInt('NSSUIVIPROD_DOLISTORE_SEVERAL_PER_DAY') && dol_print_date($lastcheck, '%Y-%m-%d', 'tzserver') == dol_print_date(dol_now(), '%Y-%m-%d', 'tzserver')) {
			return 3;
		}
		if (empty($force) && empty($this->dolistore_id) && $skipnotfounddays > 0 && $lastcheck > dol_now() - $skipnotfounddays * 86400) {
			return 2;
		}

		$knownid = (int) $this->dolistore_id;
		$searches = array();
		if ($knownid && (string) $this->dolistore_label !== '') {
			$searches[] = array((string) $this->dolistore_label, $knownid);
		}
		foreach (array_unique(array_filter(array(trim((string) $this->ref), trim((string) $this->label)))) as $name) {
			$searches[] = array($name, $knownid);
		}
		$found = false;
		$reached = false;
		foreach ($searches as $search) {
			list($name, $id) = $search;
			$products = self::searchDolistore($name);
			if ($products === null) {
				continue;
			}
			$reached = true;
			$candidates = array();
			foreach ($products as $product) {
				if ($id && (int) $product['id'] == $id) {
					$candidates = array($product);
					break;
				}
				// Label of the product beginning with the name (followed by nothing, a space or a punctuation)
				if (!$id && preg_match('/^'.preg_quote(dol_strtolower($name), '/').'($|[^a-z0-9])/u', dol_strtolower(trim((string) $product['label'])))) {
					$candidates[] = $product;
				}
			}
			if (count($candidates) == 1) {
				$found = $candidates[0];
				break;
			}
		}
		if (!$reached) {
			$langs->load("nssuiviprod@nssuiviprod");
			$this->error = $langs->trans('ErrorDolistoreNotReachable');
			$this->errors[] = $this->error;
			return -1;
		}

		$now = dol_now();
		$sql = "UPDATE ".$this->db->prefix().$this->table_element." SET";
		$sql .= " dolistore_date = '".$this->db->idate($now)."'";
		if ($found) {
			$sql .= ", dolistore_id = ".((int) $found['id']);
			$sql .= ", dolistore_label = '".$this->db->escape(dol_substr((string) $found['label'], 0, 255))."'";
			$sql .= ", dolistore_ref = '".$this->db->escape(dol_substr((string) (isset($found['ref']) ? $found['ref'] : ''), 0, 128))."'";
			$sql .= ", dolistore_version = '".$this->db->escape(dol_substr((string) $found['module_version'], 0, 64))."'";
		}
		$sql .= ", fk_user_modif = ".((int) $user->id);
		$sql .= " WHERE rowid = ".((int) $this->id);
		if (!$this->db->query($sql)) {
			$this->error = $this->db->lasterror();
			$this->errors[] = $this->error;
			return -1;
		}
		$this->dolistore_date = $now;
		if ($found) {
			$this->dolistore_id = (int) $found['id'];
			$this->dolistore_label = dol_substr((string) $found['label'], 0, 255);
			$this->dolistore_ref = dol_substr((string) (isset($found['ref']) ? $found['ref'] : ''), 0, 128);
			$this->dolistore_version = dol_substr((string) $found['module_version'], 0, 64);
		}

		return ($found ? 1 : 0);
	}

