	/**
	 * Quick check that the database of the module is up to date (no migration to run): version saved by the activation
	 * of the module, otherwise (activation of a former version) the table of the modules exists and every plugin is
	 * linked to its module
	 *
	 * @param	DoliDB	$db		Database handler
	 * @return	bool			true if up to date
	 */
	public static function isDatabaseUpToDate($db)
	{
		static $uptodate = null;

		if ($uptodate === null) {
			$uptodate = (version_compare(getDolGlobalString('NSSUIVIPROD_DB_VERSION', '0'), self::DB_VERSION, '>='));
			if (!$uptodate) {
				$resql = $db->query("SELECT COUNT(rowid) as nb FROM ".$db->prefix()."nssuiviprod_siteplugin WHERE fk_module IS NULL");
				$obj = ($resql ? $db->fetch_object($resql) : null);
				$uptodate = ($obj && (int) $obj->nb == 0 && $db->query("SELECT rowid, fk_product FROM ".$db->prefix()."nssuiviprod_pluginmodule WHERE 1 = 0"));
			}
		}

		return $uptodate;
	}

