	/**
	 * Scheduled job (daily): check of the current version on the Dolistore of the modules installed on at least one URL
	 * of a site. A module already checked today is not asked again (unless the setup allows several checks a day), a
	 * module not found during the last 7 days is not searched again.
	 *
	 * @return	int		0 if OK, 1 if the Dolistore could not be reached (result in $this->output)
	 */
	public function cronCheckDolistore()
	{
		global $user, $langs;

		$langs->load("nssuiviprod@nssuiviprod");
		$this->output = '';
		$sql = "SELECT t.rowid FROM ".$this->db->prefix().$this->table_element." as t";
		$sql .= " WHERE t.entity IN (".getEntity($this->element).")";
		$sql .= " AND EXISTS (SELECT sp.rowid FROM ".$this->db->prefix()."nssuiviprod_siteplugin as sp WHERE sp.fk_module = t.rowid)";
		$sql .= " ORDER BY t.dolistore_date ASC";	// Modules checked for the longest time first
		$resql = $this->db->query($sql);
		if (!$resql) {
			$this->error = $this->db->lasterror();
			$this->output = $this->error;
			return 1;
		}
		$ids = array();
		while ($obj = $this->db->fetch_object($resql)) {
			$ids[] = (int) $obj->rowid;
		}
		$this->db->free($resql);
		self::preload($this->db, $ids);

		$counts = array('found' => 0, 'notfound' => 0, 'skipped' => 0, 'error' => 0);
		foreach ($ids as $id) {
			$module = self::getCached($this->db, $id);
			if (!$module) {
				continue;
			}
			$res = $module->checkDolistoreVersion($user, 7, 0);
			if ($res == 1) {
				$counts['found']++;
			} elseif ($res == 0) {
				$counts['notfound']++;
			} elseif ($res > 1) {
				$counts['skipped']++;
			} else {
				$counts['error']++;
				$this->error = $module->error;
				break;	// Dolistore not reachable: the next modules would fail too
			}
		}
		$this->output = $langs->transnoentitiesnoconv('NssuiviprodCronDolistoreResult', count($ids), $counts['found'], $counts['notfound'], $counts['skipped']).($counts['error'] ? ' '.$this->error : '');

		return ($counts['error'] ? 1 : 0);
	}

	/**
	 * Migration of the plugins recorded before the table of the modules (version 23.0.2): one module by technical name
	 * (or label of a plugin entered by hand) and entity, made from the information of its last plugin (Dolistore
	 * information of its last plugin found on the Dolistore), then the plugins are linked to it. Run at each activation
	 * of the module: nothing is done when all the plugins are already linked to a module.
	 *
	 * @param	DoliDB	$db		Database handler
	 * @return	array{created:int,linked:int}|int<-1,-1>	Number of modules created and of plugins linked, -1 if error
	 */
	public static function migrateFromPlugins($db)
	{
		$result = array('created' => 0, 'linked' => 0);
		$identity = array('label', 'module_class', 'module_number', 'module_description', 'publisher', 'publisher_url', 'family', 'url_last_version');
		$dolistore = array('dolistore_id', 'dolistore_ref', 'dolistore_label', 'dolistore_version', 'dolistore_date');

		// Plugins not yet linked to a module, the most recent first (former columns of the plugins)
		$sql = "SELECT p.rowid, p.entity, p.ref, p.label, p.module_name, p.date_creation, p.fk_user_creat, p.import_key, p.".implode(', p.', array_merge(array_slice($identity, 1), $dolistore));
		$sql .= " FROM ".$db->prefix()."nssuiviprod_siteplugin as p WHERE p.fk_module IS NULL ORDER BY p.rowid DESC";
		$resql = $db->query($sql);
		if (!$resql) {
			return -1;
		}
		$groups = array();
		while ($obj = $db->fetch_object($resql)) {
			$name = trim((string) $obj->module_name);
			if ($name === '') {
				$name = trim((string) ($obj->label !== '' && $obj->label !== null ? $obj->label : $obj->ref));
			}
			if ($name === '') {
				continue;
			}
			$groups[(int) $obj->entity.'|'.dol_strtolower(dol_substr($name, 0, 128))][] = array('name' => dol_substr($name, 0, 128), 'obj' => $obj);
		}
		$db->free($resql);
		if (!count($groups)) {
			return $result;
		}

		$db->begin();
		foreach ($groups as $group) {
			$last = $group[0]['obj'];
			$name = $group[0]['name'];
			// Existing module of this name in the entity of the plugins
			$sql = "SELECT m.rowid FROM ".$db->prefix()."nssuiviprod_pluginmodule as m";
			$sql .= " WHERE m.entity = ".((int) $last->entity)." AND LOWER(m.ref) = '".$db->escape(dol_strtolower($name))."'";
			$resql = $db->query($sql);
			if (!$resql) {
				$db->rollback();
				return -1;
			}
			$objm = $db->fetch_object($resql);
			$db->free($resql);
			if ($objm) {
				$moduleid = (int) $objm->rowid;
			} else {
				// Dolistore information of the last plugin of the module found on the Dolistore
				$found = null;
				foreach ($group as $item) {
					if ((int) $item['obj']->dolistore_id > 0 && (!$found || (string) $item['obj']->dolistore_date > (string) $found->dolistore_date)) {
						$found = $item['obj'];
					}
				}
				$values = array(
					'entity' => (int) $last->entity,
					'ref' => "'".$db->escape($name)."'",
					'label' => "'".$db->escape(trim((string) $last->label) !== '' ? (string) $last->label : $name)."'",
					'date_creation' => ($last->date_creation ? "'".$db->escape((string) $last->date_creation)."'" : "'".$db->idate(dol_now())."'"),
					'fk_user_creat' => (int) $last->fk_user_creat,
					'import_key' => ((string) $last->import_key !== '' ? "'".$db->escape((string) $last->import_key)."'" : 'NULL'),
				);
				foreach (array_slice($identity, 1) as $key) {
					$values[$key] = ($last->$key === null || (string) $last->$key === '' ? 'NULL' : ($key == 'module_number' ? (int) $last->$key : "'".$db->escape((string) $last->$key)."'"));
				}
				foreach ($dolistore as $key) {
					$value = ($found ? $found->$key : $last->$key);
					$values[$key] = ($value === null || (string) $value === '' ? 'NULL' : ($key == 'dolistore_id' ? (int) $value : "'".$db->escape((string) $value)."'"));
				}
				$sql = "INSERT INTO ".$db->prefix()."nssuiviprod_pluginmodule (".implode(', ', array_keys($values)).") VALUES (".implode(', ', $values).")";
				if (!$db->query($sql)) {
					$db->rollback();
					return -1;
				}
				$moduleid = (int) $db->last_insert_id($db->prefix()."nssuiviprod_pluginmodule");
				$result['created']++;
			}
			$ids = array();
			foreach ($group as $item) {
				$ids[] = (int) $item['obj']->rowid;
			}
			$sql = "UPDATE ".$db->prefix()."nssuiviprod_siteplugin SET fk_module = ".((int) $moduleid)." WHERE rowid IN (".$db->sanitize(implode(',', $ids)).") AND fk_module IS NULL";
			if (!$db->query($sql)) {
				$db->rollback();
				return -1;
			}
			$result['linked'] += count($ids);
		}
		$db->commit();

		return $result;
	}

