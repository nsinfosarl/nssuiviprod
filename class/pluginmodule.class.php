	public static $cache = array();

	/**
	 * Return a module, loaded once by page (cache)
	 *
	 * @param	DoliDB	$db		Database handler
	 * @param	int		$id		Id of the module
	 * @return	PluginModule|null	Module, null if not found
	 */
	public static function getCached($db, $id)
	{
		$id = (int) $id;
		if ($id <= 0) {
			return null;
		}
		if (!array_key_exists($id, self::$cache)) {
			self::preload($db, array($id));
		}

		return (self::$cache[$id] ? self::$cache[$id] : null);
	}

	/**
	 * Load several modules in the cache with one request (lists of plugins)
	 *
	 * @param	DoliDB	$db		Database handler
	 * @param	int[]	$ids	Ids of the modules
	 * @return	void
	 */
	public static function preload($db, $ids)
	{
		$ids = array_diff(array_unique(array_filter(array_map('intval', $ids))), array_keys(self::$cache));
		if (!count($ids)) {
			return;
		}
		$tmp = new self($db);
		$sql = "SELECT ".$tmp->getFieldList('t')." FROM ".$db->prefix().$tmp->table_element." as t";
		$sql .= " WHERE t.rowid IN (".$db->sanitize(implode(',', $ids)).")";
		$resql = $db->query($sql);
		foreach ($ids as $id) {
			self::$cache[$id] = false;
		}
		if ($resql) {
			while ($obj = $db->fetch_object($resql)) {
				$module = new self($db);
				$module->setVarsFromFetchObj($obj);
				self::$cache[(int) $module->id] = $module;
			}
			$db->free($resql);
		}
	}

	/**
	 * Return the id of the module of a technical name (or label of a plugin entered by hand), in the current entity
	 *
	 * @param	DoliDB	$db		Database handler
	 * @param	string	$name	Technical name
	 * @return	int				Id of the module, 0 if none, -1 if error
	 */
	public static function findByName($db, $name)
	{
		$name = trim((string) $name);
		if ($name === '') {
			return 0;
		}
		$sql = "SELECT t.rowid FROM ".$db->prefix()."nssuiviprod_pluginmodule as t";
		$sql .= " WHERE LOWER(t.ref) = '".$db->escape(dol_strtolower($name))."'";
		$sql .= " AND t.entity IN (".getEntity('pluginmodule').")";
		$sql .= " ORDER BY t.rowid ASC";
		$resql = $db->query($sql);
		if (!$resql) {
			return -1;
		}
		$obj = $db->fetch_object($resql);
		$db->free($resql);

		return ($obj ? (int) $obj->rowid : 0);
	}

	/**
	 * Return the module of a technical name, created if it does not exist. The information given (import of the JSON
	 * file of the external modules) updates the module when it differs.
	 *
	 * @param	DoliDB					$db		Database handler
	 * @param	User					$user	User that creates or updates
	 * @param	string					$name	Technical name (or label of a plugin entered by hand)
	 * @param	array<string,mixed>		$data	Information of the module (fields of the module), empty to keep the module as it is
	 * @return	PluginModule|null				Module, null if error (error in $db->lasterror())
	 */
	public static function findOrCreate($db, User $user, $name, $data = array())
	{
		$name = dol_substr(trim((string) $name), 0, 128);
		$id = self::findByName($db, $name);
		if ($id < 0) {
			return null;
		}
		$module = ($id > 0 ? self::getCached($db, $id) : null);
		if (!$module) {
			$module = new self($db);
			$module->ref = $name;
			$module->label = $name;
			foreach ($data as $key => $value) {
				if (isset($module->fields[$key]) && !in_array($key, array('rowid', 'entity', 'ref'))) {
					$module->$key = $value;
				}
			}
			if ($module->create($user) <= 0) {
				return null;
			}
			self::$cache[(int) $module->id] = $module;

			return $module;
		}
		// Information of the import: module updated only if something changed (label and import key kept from the creation:
		// the same module may have another label on another site)
		$changed = false;
		foreach ($data as $key => $value) {
			if (isset($module->fields[$key]) && !in_array($key, array('rowid', 'entity', 'ref', 'label', 'import_key')) && (string) $value !== '' && (string) $module->$key !== (string) $value) {
				$module->$key = $value;
				$changed = true;
			}
		}
		if ($changed && $module->update($user) <= 0) {
			return null;
		}

		return $module;
	}

