			$dir = $conf->nssuiviprod->dir_output;
		} else {
			$dir = DOL_DATA_ROOT.($conf->entity > 1 ? '/'.((int) $conf->entity) : '').'/nssuiviprod';
		}

		// Name of the file: address of the instance (module nslistmodexterne), else its former name
		$name = 'modules_externes.json';
		if (dol_include_once('/nslistmodexterne/class/listmodexterne.class.php') && class_exists('ListModExterne') && method_exists('ListModExterne', 'getFileName')) {
			$name = ListModExterne::getFileName();
