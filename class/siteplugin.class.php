	/**
	 * Search products on the Dolistore (public API used by Dolibarr, see admin/remotestore)
	 *
	 * @param	string	$search		Text to search (at least 2 characters)
	 * @return	array<int,array<string,mixed>>|null	Products found (id, label, module_version...), null if the Dolistore can't be reached
	 */
	public static function searchDolistore($search)
	{
		static $cache = array();

		$search = trim((string) $search);
		if (dol_strlen(str_replace(' ', '', $search)) < 2) {
			return array();
		}
		if (array_key_exists($search, $cache)) {
			return $cache[$search];
		}
		require_once DOL_DOCUMENT_ROOT.'/core/lib/geturl.lib.php';
		$apiurl = getDolGlobalString('MAIN_MODULE_DOLISTORE_API_SRV', 'https://www.dolistore.com/api/');
		$apikey = getDolGlobalString('MAIN_MODULE_DOLISTORE_API_KEY', 'dolistorepublicapi');
		$url = $apiurl.(preg_match('/\/$/', $apiurl) ? '' : '/').'products?'.http_build_query(array('search' => $search, 'limit' => 20, 'page' => 1, 'lang' => 'fr_FR', 'apikey' => $apikey));
		$response = getURLContent($url, 'GET', '', 1, array('DOLAPIKEY: '.$apikey), array('https'), 0, -1, 5, 10);
		if (empty($response['http_code']) || $response['http_code'] != 200) {
			return null;	// Not cached: the Dolistore may answer at the next call
		}
		$data = json_decode((string) $response['content'], true);
		$cache[$search] = (is_array($data) && !empty($data['products']) && is_array($data['products'])) ? $data['products'] : array();

		return $cache[$search];
	}

	/**
	 * Get the current version of the plugin on the Dolistore and save it (with the Dolistore id and label of the product
	 * and the date of the check).
	 * Once a module is identified on the Dolistore, its id and label are reused for all the plugins of this module (same
	 * technical name, whatever the site or the customer): one search on the exact label of the product is then enough.
	 * Otherwise the product is the only one whose label begins with the technical name or the label of the plugin.
	 *
	 * @param	User	$user				User that checks
	 * @param	int		$skipnotfounddays	Do not search again a module not found on the Dolistore during the last days (0=always search)
	 * @return	int<-1,2>					1 if found, 0 if not found on the Dolistore, 2 if skipped (not found recently), -1 if error (Dolistore not reachable)
	 */
	public function checkDolistoreVersion(User $user, $skipnotfounddays = 0)
	{
		global $langs;
		static $bymodule = array();	// Result of the search for each module during this call of the page: product or false

		$modulekey = dol_strtolower(trim((string) ($this->module_name ? $this->module_name : $this->label)));
		if ($modulekey === '') {
			return 0;
		}

		if (!array_key_exists($modulekey, $bymodule)) {
			// Dolistore id and label already known for this module (this plugin, or a plugin of the same module of any site)
			$knownid = (int) $this->dolistore_id;
			$knownlabel = (string) $this->dolistore_label;
			if ((empty($knownid) || $knownlabel === '') && (string) $this->module_name !== '') {
				$sql = "SELECT dolistore_id, dolistore_label FROM ".$this->db->prefix().$this->table_element;
				$sql .= " WHERE module_name = '".$this->db->escape($this->module_name)."' AND dolistore_id > 0";
				$sql .= " AND entity IN (".getEntity($this->element).")";
				$sql .= " ORDER BY dolistore_date DESC";
				$resql = $this->db->query($sql);
				if ($resql && ($obj = $this->db->fetch_object($resql))) {
					$knownid = (int) $obj->dolistore_id;
					$knownlabel = (string) $obj->dolistore_label;
				}
			}

			// Module not found recently (on this plugin or on a plugin of the same module of any site): not searched again
			if (empty($knownid) && $skipnotfounddays > 0) {
				$lastcheck = (!empty($this->dolistore_date) ? (int) $this->dolistore_date : 0);
				if ((string) $this->module_name !== '') {
					$sql = "SELECT MAX(dolistore_date) as lastcheck FROM ".$this->db->prefix().$this->table_element;
					$sql .= " WHERE module_name = '".$this->db->escape($this->module_name)."' AND (dolistore_id IS NULL OR dolistore_id = 0)";
					$sql .= " AND entity IN (".getEntity($this->element).")";
					$resql = $this->db->query($sql);
					if ($resql && ($obj = $this->db->fetch_object($resql)) && $obj->lastcheck) {
						$lastcheck = max($lastcheck, (int) $this->db->jdate($obj->lastcheck));
					}
				}
				if ($lastcheck > dol_now() - $skipnotfounddays * 86400) {
					return 2;
				}
			}

			$found = false;
			$reached = false;
			$searches = array();
			if ($knownid && $knownlabel !== '') {
				$searches[] = array($knownlabel, $knownid);
			}
			foreach (array_unique(array_filter(array(trim((string) $this->module_name), trim((string) $this->label)))) as $name) {
				$searches[] = array($name, $knownid);
			}
			foreach ($searches as $search) {
				list($name, $id) = $search;
				$products = self::searchDolistore($name);
				if ($products === null) {
					continue;
				}
				$reached = true;
				$candidates = array();
				foreach ($products as $product) {
					if ($id && (int) $product['id'] == $id) {
						$candidates = array($product);
						break;
					}
					// Label of the product beginning with the name (followed by nothing, a space or a punctuation)
					if (!$id && preg_match('/^'.preg_quote(dol_strtolower($name), '/').'($|[^a-z0-9])/u', dol_strtolower(trim((string) $product['label'])))) {
						$candidates[] = $product;
					}
				}
				if (count($candidates) == 1) {
					$found = $candidates[0];
					break;
				}
			}
			if (!$reached) {
				$langs->load("nssuiviprod@nssuiviprod");
				$this->error = $langs->trans('ErrorDolistoreNotReachable');
				$this->errors[] = $this->error;
				return -1;
			}
			$bymodule[$modulekey] = $found;
		}
		$found = $bymodule[$modulekey];

		$now = dol_now();
		$sql = "UPDATE ".$this->db->prefix().$this->table_element." SET";
		$sql .= " dolistore_date = '".$this->db->idate($now)."'";
		if ($found) {
			$sql .= ", dolistore_id = ".((int) $found['id']);
			$sql .= ", dolistore_label = '".$this->db->escape(dol_substr((string) $found['label'], 0, 255))."'";
			$sql .= ", dolistore_ref = '".$this->db->escape(dol_substr((string) (isset($found['ref']) ? $found['ref'] : ''), 0, 128))."'";
			$sql .= ", dolistore_version = '".$this->db->escape(dol_substr((string) $found['module_version'], 0, 64))."'";
		}
		$sql .= ", fk_user_modif = ".((int) $user->id);
		$sql .= " WHERE rowid = ".((int) $this->id);
		if (!$this->db->query($sql)) {
			$this->error = $this->db->lasterror();
			$this->errors[] = $this->error;
			return -1;
		}
		$this->dolistore_date = $now;
		if ($found) {
			$this->dolistore_id = (int) $found['id'];
			$this->dolistore_label = dol_substr((string) $found['label'], 0, 255);
			$this->dolistore_ref = dol_substr((string) (isset($found['ref']) ? $found['ref'] : ''), 0, 128);
			$this->dolistore_version = dol_substr((string) $found['module_version'], 0, 64);
		}

		return ($found ? 1 : 0);
	}

