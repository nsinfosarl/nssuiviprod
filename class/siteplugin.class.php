	/**
	 * Import the plugins of a site from the JSON file of the external modules (module nslistmodexterne).
	 * A plugin of the site is updated when its technical name (or else its label) matches the module, otherwise it is
	 * created. The plugin is linked to the product of the plugins whose reference or label matches the module.
	 *
	 * @param	User					$user		User that imports
	 * @param	int						$fk_site	Id of the site
	 * @param	array<string,mixed>		$data		Content of the JSON file (decoded)
	 * @param	int						$fk_siteurl	Id of the URL of the site (instance) of the plugins
	 * @return	array{created:int,updated:int,linked:int,added:string[],missing:string[]}|int<-1,-1>	Number of plugins created / updated / linked to a product, labels of the plugins added and of the plugins already imported but absent from the file, -1 if KO
	 */
	public function importFromJson(User $user, $fk_site, $data, $fk_siteurl = 0)
	{
		global $langs;

		$langs->load("nssuiviprod@nssuiviprod");
		if (!is_array($data) || (isset($data['generator']) && $data['generator'] != 'nslistmodexterne') || empty($data['modules']) || !is_array($data['modules'])) {
			$this->error = $langs->trans('ErrorPluginJsonInvalid');
			$this->errors[] = $this->error;
			return -1;
		}

		// Plugins already recorded for the URL of the site, by technical name and by label
		$existing = $this->fetchAll('ASC', 't.rowid', 0, 0, '(t.fk_site:=:'.((int) $fk_site).') AND (t.fk_siteurl:=:'.((int) $fk_siteurl).')');
		if (!is_array($existing)) {
			return -1;
		}
		$byname = array();
		$bylabel = array();
		foreach ($existing as $plugin) {
			if ((string) $plugin->module_name !== '') {
				$byname[dol_strtolower($plugin->module_name)] = $plugin;
			}
			if (trim((string) $plugin->label) !== '') {
				$bylabel[dol_strtolower(trim($plugin->label))] = $plugin;
			}
		}

		$productmaps = self::getPluginProductMaps($this->db);	// Products of the plugins

		$jsondate = (!empty($data['generated_at']) ? strtotime($data['generated_at']) : false);
		$importkey = dol_print_date(dol_now(), '%Y%m%d%H%M%S', 'gmt');	// Same format as the creation date in getImportStates()
		$result = array('created' => 0, 'updated' => 0, 'linked' => 0, 'added' => array(), 'missing' => array());
		$touched = array();

		$this->db->begin();
		foreach ($data['modules'] as $module) {
			if (!is_array($module) || empty($module['name'])) {
				continue;
			}
			$name = (string) $module['name'];
			$label = trim((string) (isset($module['label']) ? $module['label'] : ''));
			$keys = array_unique(array_filter(array(dol_strtolower($name), dol_strtolower($label))));

			$plugin = null;
			if (isset($byname[dol_strtolower($name)])) {
				$plugin = $byname[dol_strtolower($name)];
			} else {
				foreach ($keys as $key) {
					if (isset($bylabel[$key]) && (string) $bylabel[$key]->module_name === '') {
						$plugin = $bylabel[$key];
						break;
					}
				}
			}
			$isnew = !is_object($plugin);
			if ($isnew) {
				$plugin = new SitePlugin($this->db);
				$plugin->fk_site = (int) $fk_site;
				$plugin->fk_siteurl = (int) $fk_siteurl;
				$plugin->label = ($label !== '' ? $label : $name);
			}

			// Product of the plugins matching the module (reference, then label)
			if (empty($plugin->fk_product)) {
				$plugin->module_name = $name;
				$productid = self::findPluginProduct($productmaps, array_unique(array_merge($keys, $plugin->getNameKeys())), (string) $plugin->dolistore_ref, (int) $plugin->rental);
				if ($productid) {
					$plugin->fk_product = $productid;
					$result['linked']++;
				}
			}

			$features = (isset($module['features']) && is_array($module['features'])) ? $module['features'] : array();
			$plugin->version = dol_substr((string) (isset($module['version']) ? $module['version'] : ''), 0, 64);
			$plugin->module_name = dol_substr($name, 0, 128);
			$plugin->module_class = dol_substr(self::jsonText($module, 'class'), 0, 128);
			$plugin->module_number = (isset($module['number']) ? (int) $module['number'] : null);
			$plugin->module_description = self::jsonText($module, 'description');
			$plugin->publisher = dol_substr(self::jsonText($module, 'publisher'), 0, 255);
			$plugin->publisher_url = dol_substr(self::jsonText($module, 'publisher_url'), 0, 255);
			$plugin->family = dol_substr(self::jsonText($module, 'family'), 0, 64);
			$plugin->module_enabled = (!empty($module['enabled']) ? 1 : 0);
			$plugin->activation_date = (!empty($module['activation_date']) ? strtotime($module['activation_date']) : '');
			$plugin->module_path = dol_substr(self::jsonText($module, 'path'), 0, 255);
			$plugin->version_file = dol_substr(self::jsonText($module, 'version_file'), 0, 64);
			$plugin->has_changelog = (!empty($module['has_changelog']) ? 1 : 0);
			$plugin->need_dolibarr_version = dol_substr(self::jsonText($module, 'need_dolibarr_version'), 0, 32);
			$plugin->php_min = dol_substr(self::jsonText($module, 'php_min'), 0, 32);
			$plugin->depends = self::jsonText($module, 'depends');
			$plugin->required_by = self::jsonText($module, 'required_by');
			$plugin->conflict_with = self::jsonText($module, 'conflict_with');
			$plugin->setup_page = dol_substr(self::jsonText($module, 'setup_page'), 0, 255);
			$plugin->lang_files = self::jsonText($module, 'lang_files');
			$plugin->url_last_version = dol_substr(self::jsonText($module, 'url_last_version'), 0, 255);
			$plugin->nb_rights = (int) (isset($features['rights']) ? $features['rights'] : 0);
			$plugin->nb_menus = (int) (isset($features['menus']) ? $features['menus'] : 0);
			$plugin->nb_tabs = (int) (isset($features['tabs']) ? $features['tabs'] : 0);
			$plugin->nb_dictionaries = (int) (isset($features['dictionaries']) ? $features['dictionaries'] : 0);
			$plugin->nb_widgets = (int) (isset($features['widgets']) ? $features['widgets'] : 0);
			$plugin->nb_cron_jobs = (int) (isset($features['cron_jobs']) ? $features['cron_jobs'] : 0);
			$plugin->has_triggers = (!empty($features['triggers']) ? 1 : 0);
			$plugin->has_models = (!empty($features['models']) ? 1 : 0);
			$plugin->hooks = self::jsonText($features, 'hooks');
			$plugin->css = self::jsonText($features, 'css');
			$plugin->js = self::jsonText($features, 'js');
			$plugin->json_date = ($jsondate ? $jsondate : '');
			$plugin->import_key = $importkey;

			$res = ($isnew ? $plugin->create($user) : $plugin->update($user));
			if ($res <= 0) {
				$this->error = $name.': '.$plugin->error;
				$this->errors = array_merge(array($this->error), $plugin->errors);
				$this->db->rollback();
				return -1;
			}
			$result[$isnew ? 'created' : 'updated']++;
			$touched[(int) $plugin->id] = 1;
			if ($isnew) {
				$byname[dol_strtolower($name)] = $plugin;
				$result['added'][] = $plugin->label;
			}
		}
		$this->db->commit();

		// Plugins already imported (technical name known) but absent from this file: reported, not deleted
		foreach ($existing as $plugin) {
			if ((string) $plugin->module_name !== '' && empty($touched[(int) $plugin->id])) {
				$result['missing'][] = $plugin->label;
			}
		}

		return $result;
	}

	/**
	 * Return the state of the plugins of a site at the last import of the JSON file of the external modules: added by
	 * the last import, or absent from the last import (imported before, but not in the last file). The plugins entered
	 * by hand (no technical name) are never reported.
	 *
	 * @param	SitePlugin[]	$plugins	Plugins of a site
	 * @return	array<int,string>			State ('new' or 'missing') of the reported plugins, by id
	 */
	public static function getImportStates($plugins)
	{
		// Each URL (instance) has its own imports
		$byurl = array();
		foreach ($plugins as $plugin) {
			$byurl[(int) $plugin->fk_siteurl][] = $plugin;
		}
		if (count($byurl) > 1) {
			$states = array();
			foreach ($byurl as $urlplugins) {
				$states += self::getImportStates($urlplugins);
			}
			return $states;
		}

		$lastkey = '';
		foreach ($plugins as $plugin) {
			if ((string) $plugin->module_name !== '' && (string) $plugin->import_key > $lastkey) {
				$lastkey = (string) $plugin->import_key;
			}
		}
		$states = array();
		if ($lastkey === '') {
			return $states;
		}
		$imports = 0;
		foreach ($plugins as $plugin) {
			if ((string) $plugin->module_name === '') {
				continue;
			}
			if ((string) $plugin->import_key !== $lastkey) {
				$states[(int) $plugin->id] = 'missing';
			} elseif (dol_print_date($plugin->date_creation, '%Y%m%d%H%M%S', 'gmt') >= $lastkey) {
				$states[(int) $plugin->id] = 'new';
			} else {
				$imports++;	// Plugin already there before the last import
			}
		}
		// First import of the site: all the plugins are new, nothing to report
		if (!$imports && !in_array('missing', $states)) {
			return array();
		}

		return $states;
	}

