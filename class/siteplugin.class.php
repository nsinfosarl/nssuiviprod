			$name = 'modules_externes.json';	// File generated by an older version of nslistmodexterne
		}

		return $dir.'/'.$name;
	}

	/**
	 * Return a value of the JSON file as a text (lists joined with a comma)
	 *
	 * @param	array<string,mixed>	$array	Array of the JSON file
	 * @param	string				$key	Key of the value
	 * @return	string
	 */
	private static function jsonText($array, $key)
	{
		if (!isset($array[$key]) || $array[$key] === null) {
			return '';
		}
		if (is_array($array[$key])) {
			return implode(', ', array_map('strval', array_filter($array[$key], 'is_scalar')));
		}

		return trim((string) $array[$key]);
	}

	/**
	 * Return the products of the plugins (category of the setup and its subcategories, or all the products if no
	 * category): reference and label in lower case, label without the prefix "Module Dolibarr - " / "Location module - ",
	 * rental product or not (reference beginning with "LOC_" or label with "Location")
	 *
	 * @param	DoliDB	$db		Database handler
	 * @return	array<int,array{ref:string,label:string,rental:bool}>	Products by id
	 */
	public static function getPluginProductMaps($db)
	{
		$products = array();
		if (isModEnabled('product') || isModEnabled('service')) {
			$pluginproducts = self::getPluginProductIds($db);
			if (!is_array($pluginproducts) || count($pluginproducts)) {
				$sql = "SELECT p.rowid, p.ref, p.label FROM ".$db->prefix()."product as p";
				$sql .= " WHERE p.entity IN (".getEntity('product').")";
				if (is_array($pluginproducts)) {
					$sql .= " AND p.rowid IN (".$db->sanitize(implode(',', $pluginproducts)).")";
				}
				$resql = $db->query($sql);
				if ($resql) {
					while ($obj = $db->fetch_object($resql)) {
						$ref = dol_strtolower(trim((string) $obj->ref));
						$label = dol_strtolower(trim((string) $obj->label));
						$products[(int) $obj->rowid] = array(
							'ref' => $ref,
							'label' => trim(preg_replace('/^(module dolibarr|location module|location|module)\s*[-–:]\s*/u', '', $label)),
							'rental' => (strpos($ref, 'loc_') === 0 || strpos($label, 'location') === 0),
						);
					}
					$db->free($resql);
				}
			}
		}

		return $products;
	}

	/**
	 * Return the product of the plugins of a plugin: reference of the product on the Dolistore (product "LOC_<ref>" if
	 * the plugin is rented), otherwise reference or label (without prefix) equal to one of the names of the plugin; a
	 * rental product for a rented plugin, a product to buy otherwise, when both exist
	 *
	 * @param	array<int,array{ref:string,label:string,rental:bool}>	$products		See getPluginProductMaps()
	 * @param	string[]												$keys			Names in lower case (technical name, label, Dolistore label...)
	 * @param	string													$dolistoreref	Reference of the product on the Dolistore
	 * @param	int														$rental			1 if the plugin is rented
	 * @return	int																		Id of the product, 0 if none
	 */
	public static function findPluginProduct($products, $keys, $dolistoreref = '', $rental = 0)
	{
		$dolistoreref = dol_strtolower(trim((string) $dolistoreref));
		$found = array();
		foreach ($products as $id => $product) {
			if ($dolistoreref !== '' && ($product['ref'] === $dolistoreref || $product['ref'] === 'loc_'.$dolistoreref)) {
				$found['dolistore'][(int) $product['rental']] = $id;
			}
			foreach ($keys as $key) {
				if ($key !== '' && ($product['ref'] === $key || $product['label'] === $key)) {
					$found['name'][(int) $product['rental']] = $id;
				}
			}
		}
		foreach (array('dolistore', 'name') as $how) {
			if (!empty($found[$how])) {
				return isset($found[$how][$rental ? 1 : 0]) ? $found[$how][$rental ? 1 : 0] : reset($found[$how]);
			}
		}

		return 0;
	}

	/**
	 * Link to a product of the plugins the plugins without product (see findPluginProduct())
	 *
	 * @param	SitePlugin[]	$plugins	Plugins
	 * @return	int							Number of plugins linked to a product, -1 if error
	 */
	public static function linkProducts($plugins)
	{
		global $db;

		$products = self::getPluginProductMaps($db);
		$nb = 0;
		foreach ($plugins as $plugin) {
			if (!empty($plugin->fk_product)) {
				continue;
			}
			$productid = self::findPluginProduct($products, $plugin->getNameKeys(), (string) $plugin->dolistore_ref, (int) $plugin->rental);
			if ($productid && $plugin->setValueFrom('fk_product', $productid, '', null, 'int', '', null) > 0) {
				$nb++;
			} elseif ($productid) {
				return -1;
			}
		}

		return $nb;
	}

	/**
	 * Names of the plugin in lower case, used to find its product: technical name, label, label on the Dolistore
	 * (without the text after " - ")
	 *
	 * @return	string[]
	 */
	public function getNameKeys()
	{
		$names = array($this->module_name, $this->label, $this->dolistore_label, preg_replace('/\s*[-–]\s.*$/u', '', (string) $this->dolistore_label));
		$keys = array();
		foreach ($names as $name) {
			$name = dol_strtolower(trim((string) $name));
			if ($name !== '' && !in_array($name, $keys)) {
				$keys[] = $name;
			}
		}

		return $keys;
	}

	/**
	 * Return the ids of the products of the category of the plugins (setup NSSUIVIPROD_PLUGIN_TAG) and of its subcategories
	 *
	 * @param	DoliDB	$db		Database handler
	 * @return	int[]|null		Ids of the products, or null if no category is set (all the products are allowed)
	 */
	public static function getPluginProductIds($db)
	{
		$tagid = getDolGlobalInt('NSSUIVIPROD_PLUGIN_TAG');
		if ($tagid <= 0 || !isModEnabled('categorie')) {
			return null;
		}
		// Category of the setup and all the categories under it
		$tagids = array($tagid);
		$parents = array($tagid);
		while (count($parents)) {
			$sql = "SELECT c.rowid FROM ".$db->prefix()."categorie as c";
			$sql .= " WHERE c.fk_parent IN (".$db->sanitize(implode(',', $parents)).") AND c.type = 0";
			$resql = $db->query($sql);
			$parents = array();
			if ($resql) {
				while ($obj = $db->fetch_object($resql)) {
					if (!in_array((int) $obj->rowid, $tagids)) {
						$tagids[] = (int) $obj->rowid;
						$parents[] = (int) $obj->rowid;
					}
				}
				$db->free($resql);
			}
		}
		$ids = array();
		$sql = "SELECT DISTINCT cp.fk_product FROM ".$db->prefix()."categorie_product as cp";
		$sql .= " WHERE cp.fk_categorie IN (".$db->sanitize(implode(',', $tagids)).")";
		$resql = $db->query($sql);
		if ($resql) {
			while ($obj = $db->fetch_object($resql)) {
				$ids[] = (int) $obj->fk_product;
			}
			$db->free($resql);
		}

		return $ids;
	}

