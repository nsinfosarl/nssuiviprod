	/**
	 * Return the URL of a site matching the address of the instance of the JSON file of the external modules
	 * (address without protocol, "www." and final "/", compared on the beginning of the URL of the site)
	 *
	 * @param	DoliDB	$db				Database handler
	 * @param	int		$fk_site		Id of the site
	 * @param	string	$instanceurl	Address of the instance (instance.url of the JSON file)
	 * @return	int						Id of the URL, 0 if none, -2 if several URLs match
	 */
	public static function findUrlOfInstance($db, $fk_site, $instanceurl)
	{
		$normalize = function ($url) {
			$url = dol_strtolower(trim((string) $url));
			$url = preg_replace('/^[a-z]+:\/\//', '', $url);
			$url = preg_replace('/^www\./', '', $url);
			return rtrim($url, '/');
		};
		$instance = $normalize($instanceurl);
		if ($instance === '') {
			return 0;
		}
		require_once __DIR__.'/siteurl.class.php';
		$siteurl = new SiteUrl($db);
		$urls = $siteurl->fetchAll('ASC', 't.rowid', 0, 0, '(t.fk_site:=:'.((int) $fk_site).')');
		$exact = array();
		$prefix = array();
		foreach ((is_array($urls) ? $urls : array()) as $tmpurl) {
			$url = $normalize($tmpurl->url);
			if ($url === $instance) {
				$exact[] = (int) $tmpurl->id;
			} elseif (strpos($url, $instance.'/') === 0) {
				$prefix[] = (int) $tmpurl->id;
			}
		}
		$found = (count($exact) ? $exact : $prefix);
		if (count($found) > 1) {
			return -2;
		}

		return (count($found) ? $found[0] : 0);
	}

	/**
	 * Return the path of the JSON file of the external modules of this instance, written by the module nslistmodexterne
	 * into the documents directory of nssuiviprod
	 *
	 * @return	string	Full path of the file (it may not exist)
	 */
	public static function getLocalJsonFilePath()
